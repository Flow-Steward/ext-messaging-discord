"""Generate the Discord API pages and the Coverage page from the step contracts.

Run from the bundle root: ``python3 scripts/build_pages.py`` (``--check`` fails when a
page is out of date). The pages list every step by group with one line on what it does
(the step's description), so they never disagree with the steps.
"""

