MAX_LISTED_FIELDS = 60


def _schema(spec: dict[str, Any], node: Any, depth: int = 0) -> dict[str, Any]:
    """``node`` with its $ref resolved."""
    while isinstance(node, dict) and "$ref" in node and depth < 10:
        node = spec["components"]["schemas"][node["$ref"].rsplit("/", 1)[-1]]
        depth += 1
    return node if isinstance(node, dict) else {}


def returned_fields(spec: dict[str, Any], method: str, path: str) -> tuple[str, list[str]]:
    """What a success answer is (object, list of objects, nothing) and its fields."""
    operation = spec["paths"][path][method.lower()]
    for status, answer in sorted(operation.get("responses", {}).items()):
        if not status.startswith("2"):
            continue
        content = (answer or {}).get("content") or {}
        media = content.get("application/json") or next(iter(content.values()), None)
        if not media:
            continue
        node = _schema(spec, media.get("schema"))
        shape = "an object"
        kind = node.get("type")
        kinds: list[Any] = kind if isinstance(kind, list) else [kind]
        if "array" in kinds:
            node, shape = _schema(spec, node.get("items")), "a list of objects"
        names: list[str] = []
        for part in [
            node,
            *[_schema(spec, a) for a in node.get("anyOf", []) + node.get("oneOf", [])],
        ]:
            for name in part.get("properties", {}):
                if name not in names:
                    names.append(name)
        if names:
            return shape, names
        return ("a value" if node.get("type") not in (None, "object") else shape), []
    return "no body", []


def _load(name: str) -> Any:
    return yaml.safe_load((ROOT / name).read_text())


def steps() -> list[dict[str, Any]]:
    """Every step: id, title, what it does, kind, inputs, connections, route, group."""
    manifest = _load("contracts/operation_manifest.yaml")["operations"]
    routes = json.loads((ROOT / "runtime/rest_routes.json").read_text())
    out = []
    for op in manifest:
        oid = op["operation_id"]
        route = routes.get(oid.removeprefix(PREFIX)) if oid.startswith(PREFIX) else None
        out.append(
            {
                "id": oid,
                "title": op["display_name"],
                "description": op["description"],
                "write": op["operation_kind"] == "action",
                "inputs": [i["name"] for i in op["inputs"] if i["name"] != "connection_ref"],
                "body_fields": _body_fields(op),
                "connections": op.get("connection_type_ids", []),
                "route": route,
                "group": group_of(oid.removeprefix(PREFIX), route["method"], route["path"])
                if route
                else None,
                "disabled": bool(route and route.get("provider_disabled")),
            }
        )
    return out


def _body_fields(op: dict[str, Any]) -> list[str]:
    """The fields of the Discord request body a step's ``body.data`` can carry."""
    body = next((i for i in op["inputs"] if i["name"] == "body"), None)
    data = ((body or {}).get("schema") or {}).get("properties", {}).get("data") or {}
    names: list[str] = []
    for part in [data, *data.get("anyOf", []), *data.get("oneOf", [])]:
        for name in (part or {}).get("properties", {}):
            if name not in names:
                names.append(name)
    return names


class _Dumper(yaml.SafeDumper):
    """Writes multi-line texts as literal blocks (``|``), as the hand-written pages do."""


def _text(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _text)


def _page(page_id: str, title: str, description: str, components: list[dict]) -> str:
    data = {
        "page_id": page_id,
        "title": title,
        "description": description,
        "components": components,
    }
    return HEADER + yaml.dump(
        data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=10_000
    )


def _markdown(
    component_id: str, title: str, body: str, *, collapsible: bool = False
) -> dict[str, Any]:
    component: dict[str, Any] = {
        "component_id": component_id,
        "type": "markdown",
        "title": title,
        "body": body,
    }
    if collapsible:
        # Rendered as a closed <details> section the user opens (extension-manifest-renderer).
        component["collapsible"] = True
    return component


def _bullet(step: dict[str, Any]) -> str:
    """One line per step: its name, what it does, and its action id."""
    text = " ".join(step["description"].strip().split())
    # The first sentence: what the step does. Permissions and details are on API coverage.
    summary = text.split(". ", 1)[0].rstrip(".") + "."
    return f"- **{step['title']}** — {summary} (`{step['id']}`)"


def pages() -> dict[str, str]:
    every = steps()
    by_group = {gid: [s for s in every if s["group"] == gid] for gid, _, _ in GROUPS}
    generated = [s for s in every if s["route"]]
    writes = sum(s["write"] for s in generated)
    lists = sum("all_pages" in s["inputs"] for s in generated)
    files = sum("file_artifacts" in s["inputs"] for s in generated)
    docs_only = json.loads((ROOT / "tests/reference/discord-docs-routes.json").read_text())
    from_docs = sorted(
        op["operationId"]
        for page in docs_only["pages"].values()
        for methods in page.values()
        for op in methods.values()
    )
    out: dict[str, str] = {}
    overview = [
        "The steps call the Discord REST API v10. Every operation of the pinned API "
        f"description has its own step: **{len(generated)} steps**, plus the everyday "
        "steps below.",
        "",
        "- **Connections.** Most steps act as your bot (**Discord bot** connection). Steps "
        "that act for a person need a **Discord OAuth2 token**; steps whose address holds a "
        "webhook or interaction token take it from a **Discord webhook or interaction "
        "token** connection. Each step names the connections it accepts.",
        "- **Permissions.** Discord checks the bot's permissions in the server and channel "
        "(for example Manage Messages or Manage Roles); a missing one is refused and nothing "
        "changes.",
        '- **Request bodies** go in `body` as `{"data": {...}}` with the fields Discord '
        "documents for the step. Files go in `file_artifacts` (workflow files) or `files` "
        "(small base64 files).",
        "- **Lists.** With `all_pages` a list step reads page after page; when it stops "
        "early, `complete` is false and `next_cursor` says where to continue.",
        "- **Rate limits.** Every step returns `rate_limit` from Discord's headers; an HTTP "
        "429 answer says how long to wait.",
        "- **Changes are sent once.** A step that changes data is never retried "
        "automatically; when its outcome is unclear it says so. Test runs never send "
        "changes.",
        "",
        "The steps by group:",
        "",
    ]
    overview += [
        f"- **{title}** ({len(by_group[gid])} steps): {line}" for gid, title, line in GROUPS
    ]
    everyday = [s for s in every if s["id"] in EVERYDAY]
    everyday.sort(key=lambda s: EVERYDAY.index(s["id"]))
    groups = [
        _markdown(
            f"steps_{gid}",
            f"{title} ({len(by_group[gid])})",
            line + "\n\n" + "\n".join(map(_bullet, by_group[gid])) + "\n",
            collapsible=True,
        )
        for gid, title, line in GROUPS
    ]
    out["ui/pages/discord-api.yaml"] = _page(
        "discord-api",
        "API",
        "Every Discord step by group, with what it does.",
        [
            _markdown("api_overview", "How the steps work", "\n".join(overview) + "\n"),
            _markdown(
                "steps_everyday",
                f"Everyday ({len(everyday)})",
                "\n".join(map(_bullet, everyday)) + "\n",
                collapsible=True,
            ),
            *groups,
        ],
    )
    disabled = [s for s in generated if s["disabled"]]
    coverage = [
        f"The pinned Discord API description (discord-api-spec) lists "
        f"{len(generated) - len(from_docs)} operations, and Discord's API documentation "
        f"(discord-api-docs) {len(from_docs)} more: **all {len(generated)} have their own "
        "step**.",
        "",
        f"- **{len(generated) - writes} reads** and **{writes} changes**. Test runs never "
        "send changes.",
        f"- **{lists} list steps** read all pages with `all_pages`; **{files} steps** send "
        "files (up to 20 MiB each).",
        "",
        "Steps by group:",
        "",
        *[f"- {title}: {len(by_group[gid])}" for gid, title, _ in GROUPS],
        "",
        "From the documentation only: " + ", ".join(f"`{PREFIX}{o}`" for o in from_docs) + ".",
        "",
        "Disabled by Discord: "
        + ", ".join(f"`{s['id']}` ({s['title']})" for s in disabled)
        + ". Discord turned it off with command permissions v2; the step answers "
        "`operation_disabled` without calling Discord.",
        "",
        "Delivered by Discord's other transports:",
        "",
        *[f"- {line}" for line in OTHER_TRANSPORTS],
        "",
        "Everyday steps on top: "
        + ", ".join(s["title"] for s in everyday)
        + ". Two archived pickers ("
        + ", ".join(f"`{a}`" for a in ARCHIVED)
        + ") stay for workflows made before the dedicated steps.",
    ]
    spec = load_spec()
    detail: list[str] = []
    routes = json.loads((ROOT / "runtime/rest_routes.json").read_text())
    for gid, title, _ in GROUPS:
        detail += [f"## {title}", ""]
        for step in by_group[gid]:
            route = step["route"]
            detail += [f"### {step['title']} (`{step['id']}`)", ""]
            detail += [f"Discord: `{route['method']} {route['path']}`.", ""]
            inputs = [i for i in step["inputs"]]
            detail += [
                "Inputs: " + (", ".join(f"`{i}`" for i in inputs) if inputs else "none") + ".",
                "",
            ]
            if step["body_fields"]:
                detail += [
                    "Body fields (`body.data`): "
                    + ", ".join(f"`{n}`" for n in step["body_fields"])
                    + ".",
                    "",
                ]
            shape, names = returned_fields(spec, route["method"], route["path"])
            if names:
                listed = names[:MAX_LISTED_FIELDS]
                more = len(names) - len(listed)
                detail += [
                    f"Returns {shape} in `response.data`, with "
                    + ", ".join(f"`{n}`" for n in listed)
                    + (f" and {more} more" if more else "")
                    + ".",
                    "",
                ]
            else:
                detail += [f"Returns {shape} in `response.data`.", ""]
            hidden = [
                name
                for name in [
                    *routes[step["id"].removeprefix(PREFIX)]["secret_path_parameters"],
                    *(sorted(FROM_CONNECTION_BODY.get(step["id"].removeprefix(PREFIX), ()))),
                ]
            ]
            for name in hidden:
                detail += [f"Not an input: `{name}` — {FROM_CONNECTION[name]}.", ""]
            if step["disabled"]:
                detail += [
                    "Discord disabled this endpoint with command permissions v2; the step "
                    "answers `operation_disabled` without calling Discord.",
                    "",
                ]
    out["ui/pages/api-coverage.yaml"] = _page(
        "api-coverage",
        "Discord API coverage",
        "Every Discord REST operation, the step that calls it, its inputs and what it returns.",
        [
            _markdown("coverage_summary", "Coverage", "\n".join(coverage) + "\n"),
            _markdown("coverage_detail", "Every operation", "\n".join(detail) + "\n"),
        ],
    )
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, text in pages().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print("out of date: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
